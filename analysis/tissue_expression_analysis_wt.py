# ------------------------------------------------------------------
# Linear regression: y ~ delta_score, with optional mutation adjustment
# ------------------------------------------------------------------

def fit_ols_model(
    data: pd.DataFrame,
    outcome: str,
    predictor: str,
    adjust_for_mutations: bool,
) -> dict | None:
    """Fit OLS model with robust standard errors."""
    model_columns = [outcome, predictor]

    if adjust_for_mutations:
        if "mutation_count" not in data.columns:
            return None
        model_columns.append("mutation_count")

    model_data = data[model_columns].copy()

    for column in model_columns:
        model_data[column] = pd.to_numeric(model_data[column], errors="coerce")

    model_data = model_data.dropna()

    if len(model_data) < 3:
        print(f"Skipping {predictor}: fewer than 3 complete observations.")
        return None

    if model_data[predictor].nunique() < 2:
        print(f"Skipping {predictor}: fewer than 2 unique predictor values.")
        return None

    predictors = [predictor]
    if adjust_for_mutations:
        if model_data["mutation_count"].nunique() < 2:
            print(
                f"Skipping adjusted model for {predictor}: "
                "mutation_count has fewer than 2 unique values."
            )
            return None
        predictors.append("mutation_count")

    X = sm.add_constant(model_data[predictors], has_constant="add")
    y = model_data[outcome]

    model = sm.OLS(y, X).fit(cov_type=OLS_COV_TYPE)
    ci = model.conf_int().loc[predictor]

    result = {
        "score": predictor,
        "score_label": pretty_label(predictor),
        "feature_family": feature_family(predictor),
        "outcome": outcome,
        "model": "adjusted_for_mutation_count" if adjust_for_mutations else "unadjusted",
        "n_variants": int(model.nobs),
        "coefficient": model.params[predictor],
        "robust_std_error": model.bse[predictor],
        "t_value": model.tvalues[predictor],
        "p_value": model.pvalues[predictor],
        "ci_lower": ci.iloc[0],
        "ci_upper": ci.iloc[1],
        "intercept": model.params["const"],
        "r_squared": model.rsquared,
        "adjusted_r_squared": model.rsquared_adj,
        "aic": model.aic,
        "bic": model.bic,
        "direction_note": delta_direction_note(predictor),
    }

    if adjust_for_mutations:
        result["mutation_count_coefficient"] = model.params.get("mutation_count", np.nan)
        result["mutation_count_p_value"] = model.pvalues.get("mutation_count", np.nan)
    else:
        result["mutation_count_coefficient"] = np.nan
        result["mutation_count_p_value"] = np.nan

    return result


