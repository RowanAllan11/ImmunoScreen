MODEL_LABELS = {
    "unadjusted": "Unadjusted",
    "adjusted_for_mutation_count": "Adjusted for mutation count",
}


def create_forest_plot(
    results_df: pd.DataFrame,
    features: list[str],
    title: str,
    output_file: Path,
) -> None:
    """Create forest plot for selected delta features."""
    plot_df = results_df.loc[
        results_df["score"].isin(features)
        & results_df["model"].isin(MODEL_LABELS)
    ].copy()

    if plot_df.empty:
        print(f"No regression rows available for forest plot: {title}")
        return

    feature_order = [
        feature
        for feature in features
        if feature in plot_df["score"].unique()
    ]

    base_positions = {
        feature: len(feature_order) - 1 - index
        for index, feature in enumerate(feature_order)
    }

    model_offsets = {
        "unadjusted": 0.12,
        "adjusted_for_mutation_count": -0.12,
    }

    model_markers = {
        "unadjusted": "o",
        "adjusted_for_mutation_count": "s",
    }

    fig, ax = plt.subplots(figsize=(10, max(4.5, len(feature_order) * 1.1)))

    for model_name in ["unadjusted", "adjusted_for_mutation_count"]:
        model_df = plot_df.loc[plot_df["model"] == model_name].copy()

        if model_df.empty:
            continue

        model_df["feature_order"] = model_df["score"].map(
            {feature: index for index, feature in enumerate(feature_order)}
        )
        model_df = model_df.sort_values("feature_order")

        y_positions = [
            base_positions[score] + model_offsets[model_name]
            for score in model_df["score"]
        ]

        lower_errors = model_df["coefficient"] - model_df["ci_lower"]
        upper_errors = model_df["ci_upper"] - model_df["coefficient"]

        ax.errorbar(
            model_df["coefficient"],
            y_positions,
            xerr=np.vstack([lower_errors, upper_errors]),
            fmt=model_markers[model_name],
            capsize=4,
            markersize=7,
            linewidth=1.5,
            label=MODEL_LABELS[model_name],
        )

    ax.axvline(0, linestyle="--", linewidth=1)

    y_ticks = [base_positions[feature] for feature in feature_order]
    y_labels = [pretty_label(feature) for feature in feature_order]

    ax.set_yticks(y_ticks)
    ax.set_yticklabels(y_labels)
    ax.set_xlabel(f"Regression coefficient for {OUTCOME_COLUMN} (95% CI)")
    ax.set_title(title)
    ax.grid(axis="x", linestyle=":", alpha=0.4)
    ax.legend(title="Model", frameon=False, loc="best")

    fig.tight_layout()
    fig.savefig(output_file, dpi=300, bbox_inches="tight")
    plt.close(fig)


