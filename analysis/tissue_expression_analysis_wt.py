# ------------------------------------------------------------------
# Helper functions
# ------------------------------------------------------------------

def safe_filename(name: str) -> str:
    """Convert a column name into a safe filename stem."""
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", str(name)).strip("_")


def numeric_series(df: pd.DataFrame, column: str) -> pd.Series:
    """Return a numeric version of a dataframe column."""
    return pd.to_numeric(df[column], errors="coerce")


def require_columns(df: pd.DataFrame, columns: list[str], source_name: str) -> None:
    """Raise a clear error if required columns are missing."""
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(
            f"{source_name} is missing required columns: "
            + ", ".join(missing)
        )


def is_delta_column(column: str) -> bool:
    """
    Identify WT-relative delta features only.

    Included examples:
        netMHCpan_top_delta_vs_WT
        netMHCpan_mean_top3_delta_vs_WT
        MHCflurry_top_delta_vs_WT
        BigMHC_top_delta_vs_WT
        netMHCpan_net_pass_change
        both_net_pass_change

    Excluded examples:
        netMHCpan_passed_count
        netMHCpan_new_passed_count
        netMHCpan_lost_passed_count
        netMHCpan_top_score
    """
    lower = column.lower()

    if "delta_vs_wt" in lower:
        return True

    if lower.endswith("net_pass_change"):
        return True

    return False


def pretty_label(column: str) -> str:
    """Human-readable labels for plots."""
    labels = {
        "netMHCpan_net_pass_change": "NetMHCpan net pass change",
        "MHCflurry_net_pass_change": "MHCflurry net pass change",
        "both_net_pass_change": "Both tools net pass change",
        "either_net_pass_change": "Either tool net pass change",
        "netMHCpan_top_delta_vs_WT": "NetMHCpan strongest delta vs WT",
        "netMHCpan_mean_top3_delta_vs_WT": "NetMHCpan mean top 3 delta vs WT",
        "netMHCpan_mean_delta_vs_WT": "NetMHCpan mean delta vs WT",
        "MHCflurry_top_delta_vs_WT": "MHCflurry strongest delta vs WT",
        "MHCflurry_mean_top3_delta_vs_WT": "MHCflurry mean top 3 delta vs WT",
        "MHCflurry_mean_delta_vs_WT": "MHCflurry mean delta vs WT",
        "BigMHC_top_delta_vs_WT": "BigMHC strongest delta vs WT",
        "BigMHC_mean_top3_delta_vs_WT": "BigMHC mean top 3 delta vs WT",
        "BigMHC_mean_delta_vs_WT": "BigMHC mean delta vs WT",
    }

    return labels.get(column, column.replace("_", " "))


def feature_family(column: str) -> str:
    """Group delta features into count, NetMHCpan, MHCflurry, BigMHC, or other."""
    lower = column.lower()

    if lower.endswith("net_pass_change"):
        return "delta_pass_counts"

    if lower.startswith("netmhcpan"):
        return "netmhcpan_delta_scores"

    if lower.startswith("mhcflurry"):
        return "mhcflurry_delta_scores"

    if lower.startswith("bigmhc"):
        return "bigmhc_delta_scores"

    return "other_delta_scores"


def delta_direction_note(column: str) -> str:
    """Interpretation note for coefficient direction."""
    lower = column.lower()

    if lower.endswith("net_pass_change"):
        return (
            "Positive values mean the variant gained more passing epitopes "
            "than it lost relative to WT."
        )

    if lower.startswith("bigmhc"):
        return (
            "Positive delta means higher BigMHC score than matched WT "
            "and therefore higher predicted immunogenicity."
        )

    if lower.startswith("netmhcpan") or lower.startswith("mhcflurry"):
        return (
            "Negative delta means a lower rank/percentile than matched WT, "
            "therefore stronger predicted presentation than WT."
        )

    return "WT-relative delta feature."


