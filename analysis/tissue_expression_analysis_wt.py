# Allele-specific delta-only tissue expression analysis
#
# Purpose
# -------
# Analyse whether WT-relative immunogenicity delta scores are associated
# with tissue expression for a single allele-specific variant score table.
#
# Keeps only:
#   1. Correlations between tissue expression and delta features
#   2. Linear regression: y ~ delta_score
#   3. Linear regression adjusted for mutation count: y ~ delta_score + mutation_count
#   4. Coefficient forest plots similar to the previous script
#
# Explicitly removes:
#   - Reverse count models
#   - Epitope count category models
#   - Top/bottom decile comparisons
#   - Non-delta absolute score modelling
#
# Expected inputs
# ---------------
# Tissue file:
#   CSV with columns:
#       gene_id  -> variant_id
#       y        -> tissue expression / relative enrichment score
#
# Immunogenicity file:
#   Allele-specific variant_immunogenicity_scores.tsv generated by the
#   WT-relative scoring script. One row per variant for one allele.

